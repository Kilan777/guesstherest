/**
 * Generates SQL that seeds the leaderboards with plausible scores.
 *
 *   node scripts/seed-leaderboards.mjs > supabase/seed/leaderboard_seed.sql
 *
 * Run the output in the Supabase SQL editor. It cannot be run from the browser
 * client: the RLS insert policy ties every client insert to the caller's own
 * auth.uid() and forbids `bot = true`, which is exactly what stops a player
 * fabricating scores. Seeding is an admin action, so it happens admin-side.
 *
 * Scores are calibrated against real playthroughs of the finished game, where a
 * clean sweep with a full streak landed between 9,100 and 12,200. So the top of
 * each board sits a little above that, and the bulk sits well below — a board
 * where every entry is near-perfect is both obviously fake and demoralising to
 * play against.
 */
import { readFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';

const GAMES_DIR = new URL('../src/games/', import.meta.url).pathname;

// Read slug + round count straight from the game definitions, so the seed can
// never drift from the registry (rounds_won must not exceed rounds).
const games = [];
for (const file of readdirSync(GAMES_DIR)) {
  if (!file.endsWith('.tsx') || file === 'stages.tsx') continue;
  const src = readFileSync(join(GAMES_DIR, file), 'utf8');
  const slug = /slug: '([a-z]+)'/.exec(src)?.[1];
  const rounds = Number(/rounds: (\d+)/.exec(src)?.[1] ?? 10);
  const levels = (/levels: \[([^\]]*)\]/.exec(src)?.[1].match(/,/g)?.length ?? 3) + 1;
  if (slug) games.push({ slug, rounds, levels });
}

const registry = readFileSync(join(GAMES_DIR, 'index.ts'), 'utf8');
const live = games.filter((g) => registry.includes(`'./${g.slug}'`) || registry.includes(`/${g.slug}';`));

// ── deterministic RNG so re-running produces the same file ──────────────────
let seed = 20260816;
const rnd = () => {
  seed = (seed * 1664525 + 1013904223) >>> 0;
  return seed / 4294967296;
};
const pick = (a) => a[Math.floor(rnd() * a.length)];
const between = (lo, hi) => lo + Math.floor(rnd() * (hi - lo + 1));

const ADJ = ['Neon','Turbo','Silent','Cosmic','Feral','Velvet','Rogue','Golden','Midnight','Electric',
  'Lucky','Rapid','Hollow','Crimson','Atomic','Wandering','Glass','Iron','Paper','Static','Amber',
  'Quiet','Bitter','Salted','Northern','Copper','Rust','Wild','Pale','Swift','Hazy','Blunt','Idle',
  'Marble','Cobalt','Dusty','Grim','Plush','Sober','Tidal'];
const NOUN = ['Otter','Comet','Falcon','Pixel','Bandit','Oracle','Machine','Ghost','Wolf','Signal',
  'Ranger','Lantern','Magpie','Vulture','Prophet','Sparrow','Circuit','Nomad','Beacon','Fox','Kettle',
  'Harbour','Ledger','Piston','Thistle','Anchor','Ferret','Marlin','Quill','Badger','Cinder','Drifter',
  'Heron','Jackal','Kestrel','Loom','Moth','Nettle','Osprey','Pelican'];

// ── 200 distinct players ────────────────────────────────────────────────────
const handles = new Set();
while (handles.size < 200) {
  const n = rnd() < 0.55 ? `${pick(ADJ)}${pick(NOUN)}` : `${pick(ADJ)}${pick(NOUN)}${between(2, 99)}`;
  if (n.length <= 20) handles.add(n);
}
const players = [...handles].map((handle) => ({
  handle,
  id: uuid(),
  // Skill is per-player and persists across games, which is what makes a board
  // look real: the same names recur near the top.
  skill: rnd(),
}));

function uuid() {
  const hex = '0123456789abcdef';
  let out = '';
  for (let i = 0; i < 32; i++) out += hex[Math.floor(rnd() * 16)];
  return `${out.slice(0, 8)}-${out.slice(8, 12)}-${out.slice(12, 16)}-${out.slice(16, 20)}-${out.slice(20)}`;
}

const esc = (s) => s.replace(/'/g, "''");
const rows = [];

for (const game of live) {
  // Not everyone plays everything.
  const field = players.filter(() => rnd() < 0.11);
  for (const p of field) {
    // Skewed low: most runs are mediocre, a few are excellent.
    const roll = Math.pow(rnd(), 1.7);
    const ability = (p.skill * 0.6 + roll * 0.4);
    const won = Math.max(1, Math.min(game.rounds, Math.round(ability * game.rounds + between(-1, 1))));
    const perRound = 380 + ability * 780;
    const streakBonus = 1 + Math.min(won, 10) * 0.045;
    const score = Math.max(150, Math.round(won * perRound * streakBonus));
    const bestStreak = Math.max(1, Math.min(won, Math.round(won * (0.45 + ability * 0.5))));
    const daysAgo = between(0, 20);
    const mins = between(0, 1439);
    rows.push(
      `  ('${game.slug}', '${p.id}', '${esc(p.handle)}', ${score}, ${won}, ${bestStreak}, true, ` +
        `now() - interval '${daysAgo} days' - interval '${mins} minutes')`,
    );
  }
}

console.log(`-- Seeded leaderboard scores for ${live.length} games.`);
console.log(`-- ${players.length} players, ${rows.length} rows. Generated by scripts/seed-leaderboards.mjs.`);
console.log(`-- Requires migration 0002_seeded_scores.sql (adds the bot column).`);
console.log(`-- Remove them all again with:  delete from public.scores where bot;`);
console.log();
console.log('insert into public.scores');
console.log('  (game_slug, player_id, handle, score, rounds_won, best_streak, bot, created_at)');
console.log('values');
console.log(rows.join(',\n') + ';');
